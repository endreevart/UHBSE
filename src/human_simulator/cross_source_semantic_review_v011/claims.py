"""Corrective claim overlays for prior-rule universe and metadata (v0.1.1)."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from human_simulator.cross_source_semantic_review_v011.policy import (
    ACCEPTED_V01_ARTIFACT_DIR,
    VERSION,
)


def load_v01_accounting(root: Path) -> dict[str, Any]:
    p = Path(root) / ACCEPTED_V01_ARTIFACT_DIR / "mapping-universe-accounting.json"
    return json.loads(p.read_text(encoding="utf-8"))


def load_v01_classification(root: Path) -> dict[str, Any]:
    p = (
        Path(root)
        / ACCEPTED_V01_ARTIFACT_DIR
        / "semantic-candidate-classification.json"
    )
    return json.loads(p.read_text(encoding="utf-8"))


def load_v01_status(root: Path) -> dict[str, Any]:
    p = Path(root) / ACCEPTED_V01_ARTIFACT_DIR / "status-contract.json"
    return json.loads(p.read_text(encoding="utf-8"))


def build_corrected_universe_claims(root: Path) -> dict[str, Any]:
    acc = load_v01_accounting(root)
    n_strata = int(acc.get("n_mapping_strata") or 0)
    n_with = int(acc.get("n_with_b_candidate") or 0)
    n_without = int(acc.get("n_without_b_candidate") or 0)
    # Prefer explicit prior-rule accounting
    no_prior_rule = n_without if n_without else max(0, n_strata - n_with)
    return {
        "version": VERSION,
        "PRIOR_RULE_MAPPING_UNIVERSE_ACCOUNTING_STATUS": (
            "PASS" if n_strata == 98 else "FAIL"
        ),
        "EXHAUSTIVE_CROSS_SOURCE_CANDIDATE_DISCOVERY_STATUS": "NOT_RUN",
        "n_mapping_strata_prior_rule": n_strata,
        "n_with_prior_rule_b_candidate": n_with,
        "NO_PRIOR_RULE_CANDIDATE_COUNT": no_prior_rule,
        "forbidden_claim": (
            "Must NOT claim that 88 outcomes have no candidates in Source B."
        ),
        "correct_claim": (
            "88 Source A provider grains had no candidate generated by the limited "
            "prior-rule candidate set; the full Source B catalog was not exhaustively searched."
        ),
        "construction": (
            "98 strata built from frozen A providers + hardcoded prior rules (T3/T4/ТТГ)."
        ),
        "prior_lineage_status_counts": acc.get("prior_lineage_status_counts"),
        "universe_hash": acc.get("universe_hash"),
        "ok": n_strata == 98 and no_prior_rule == 88,
    }


def build_metadata_status() -> dict[str, Any]:
    return {
        "version": VERSION,
        "SOURCE_A_SPECIMEN_METADATA_STATUS": "NOT_AVAILABLE_IN_PROVIDER_REGISTRY",
        "SOURCE_A_ASSAY_METADATA_STATUS": "NOT_AVAILABLE_IN_PROVIDER_REGISTRY",
        "SOURCE_B_SPECIMEN_METADATA_STATUS": "NOT_AVAILABLE_FOR_CURRENT_CANDIDATES",
        "SOURCE_B_ASSAY_METADATA_STATUS": "NOT_AVAILABLE_FOR_CURRENT_CANDIDATES",
        "note": (
            "Missing specimen/assay metadata is not solely a Source B problem; "
            "Source A provider registry also lacks specimen/assay fields."
        ),
        "ok": True,
    }


def build_readiness_correction(root: Path) -> dict[str, Any]:
    thr_path = Path(root) / ACCEPTED_V01_ARTIFACT_DIR / "threshold-options.json"
    thr = json.loads(thr_path.read_text(encoding="utf-8")) if thr_path.is_file() else {}
    return {
        "version": VERSION,
        "OUTCOME_SPECIFIC_B_SPLIT_ACCOUNTING_STATUS": "NOT_COMPUTED",
        "split_counts_are_aggregate_only": True,
        "THRESHOLD_DECISION_REQUIRED": True,
        "THRESHOLD_OWNER_DECISION_STATUS": "DEFERRED_UNTIL_EXHAUSTIVE_DISCOVERY",
        "threshold_options_non_authoritative": thr.get("options") or [
            {"option_id": "T1", "min_scientifically_usable_accepted": 1},
            {"option_id": "T3", "min_scientifically_usable_accepted": 3},
            {"option_id": "T5", "min_scientifically_usable_accepted": 5},
        ],
        "owner_threshold_accepted_in_this_release": False,
        "note": "T1/T3/T5 remain non-authoritative options only.",
        "ok": True,
    }
