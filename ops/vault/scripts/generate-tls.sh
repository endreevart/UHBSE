#!/usr/bin/env bash
# Generate private-network TLS material for UHBSE Vault.
# Output is written under ops/vault/tls/ (git-ignored). Never commit certs/keys.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "${SCRIPT_DIR}/../../.." && pwd)"
TLS_DIR="${ROOT}/ops/vault/tls"
mkdir -p "${TLS_DIR}"

CN="${VAULT_TLS_CN:-vault.uhbse.local}"
DAYS="${VAULT_TLS_DAYS:-825}"

if [ -f "${TLS_DIR}/server.crt" ] && [ -f "${TLS_DIR}/server.key" ] && [ "${VAULT_TLS_FORCE:-0}" != "1" ]; then
  echo "TLS material already present in ops/vault/tls/ (set VAULT_TLS_FORCE=1 to regenerate)."
  exit 0
fi

openssl req -x509 -newkey rsa:4096 -sha256 -nodes \
  -keyout "${TLS_DIR}/server.key" \
  -out "${TLS_DIR}/server.crt" \
  -days "${DAYS}" \
  -subj "/CN=${CN}/O=UHBSE/OU=Stage03-Alignment" \
  -addext "subjectAltName=DNS:${CN},DNS:localhost,DNS:vault,IP:127.0.0.1"

chmod 600 "${TLS_DIR}/server.key"
chmod 644 "${TLS_DIR}/server.crt"
cp "${TLS_DIR}/server.crt" "${TLS_DIR}/ca.crt"

cat > "${TLS_DIR}/README.md" <<'EOF'
# Vault TLS (local, git-ignored)

Generated by ops/vault/scripts/generate-tls.sh.

- server.crt / server.key — mounted into the Vault container
- ca.crt — trust anchor for local CLI / preflight (VAULT_CACERT)

Do not commit this directory. Rotate by regenerating with VAULT_TLS_FORCE=1.
EOF

echo "Wrote TLS material under ops/vault/tls/ (git-ignored)."
